function enc(pts) {
  let s = '', px = 0, py = 0;
  const put = (v) => { let u = v < 0 ? ~(v << 1) : (v << 1); while (u >= 32) { s += String.fromCharCode((32 | (u & 31)) + 63); u >>>= 5; } s += String.fromCharCode(u + 63); };
  for (let k = 0; k + 1 < pts.length; k += 2) { const x = Math.round(pts[k] * 64), y = Math.round(pts[k + 1] * 64); put(x - px); put(y - py); px = x; py = y; }
  return s;
}
